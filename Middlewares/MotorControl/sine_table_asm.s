;===========================================================
; sine_table.s
; 正弦表（汇编版，用于与 sine_table.c 的 C 数组做对照）
;
; 架构：dsPIC33EP128MC506（16 位字寻址，FCY=70MHz）
; 数据宽度：.hword = 16 位半字 = C 的 int16_t（负数自动补码编码，
;           如 -32768 -> 0x8000，与 Q1.15 定点一致）
; 段属性：.const 段 + psv 属性，与 C 的 const int16_t[] 同机制（PSV 窗口可直接读）
;
; 内容：128 点 Q1.15 正弦表，0~360°，步长 2.8125°
;       由 0°~90° 共 33 个基础值经 1/4 波对称生成（见 sine_table.h）
;       值与 sine_table.c:s_sine_table 逐项一致，可逐行比对。
;
; 符号：_SinTable（C 侧 __SinTable），与 C 的 static
;       s_sine_table 不同名，故二者并存无冲突。本表仅供对照，
;       默认不参与业务逻辑。因位于 .const + psv，C 侧若需读取可用
;       extern const int16_t _SinTable[128]; 直接索引（PSV 自动管理）。
;
; 关键校验点：
;   idx[ 0]  =       0   (0°   过零)
;   idx[32]  =   32767   (90°  正峰，+1.0 裁剪)
;   idx[64]  =       0   (180° 过零)
;   idx[96]  =  -32768   (270° 负峰，-1.0 精确 0x8000)
;   idx[127] =   -1608   (357.1875°)
;===========================================================

    .include "p33EP128MC506.inc"

    ;---- 表参数
    .equ    SINE_TABLE_SIZE, 128

    .section .const, psv
    .global _SinTable

_SinTable:
    ;--- Q1: 0° ~ 90° (idx 0~32) — 直接取基础值 ---
    ;[  0]
    .hword      0,   1608,   3212,   4808,   6393,   7962,   9512,  11039
    ;[  8]
    .hword  12540,  14010,  15447,  16846,  18205,  19520,  20788,  22006
    ;[ 16]
    .hword  23170,  24279,  25330,  26320,  27246,  28106,  28899,  29622
    ;[ 24]
    .hword  30274,  30853,  31357,  31786,  32138,  32413,  32610,  32729
    ;[ 32] ← 90° 正峰（+1.0 裁剪自 32768）
    .hword  32767

    ;--- Q2: 90° ~ 180° (idx 33~63) — 镜像 q[64-i] ---
    ;[ 33]
    .hword  32729,  32610,  32413,  32138,  31786,  31357,  30853,  30274
    ;[ 41]
    .hword  29622,  28899,  28106,  27246,  26320,  25330,  24279,  23170
    ;[ 49]
    .hword  22006,  20788,  19520,  18205,  16846,  15447,  14010,  12540
    ;[ 57]
    .hword  11039,   9512,   7962,   6393,   4808,   3212,   1608
    ;[ 64] ← 180° 过零
    .hword      0

    ;--- Q3: 180° ~ 270° (idx 65~96) — 取反 q[i-64] ---
    ;[ 65]
    .hword  -1608,  -3212,  -4808,  -6393,  -7962,  -9512, -11039
    ;[ 72]
    .hword -12540, -14010, -15447, -16846, -18205, -19520, -20788, -22006
    ;[ 80]
    .hword -23170, -24279, -25330, -26320, -27246, -28106, -28899, -29622
    ;[ 88]
    .hword -30274, -30853, -31357, -31786, -32138, -32413, -32610, -32729
    ;[ 96] ← 270° 负峰（-1.0 精确，0x8000）
    .hword -32768

    ;--- Q4: 270° ~ 360° (idx 97~127) — 取反镜像 q[128-i] ---
    ;[ 97]
    .hword -32729, -32610, -32413, -32138, -31786, -31357, -30853, -30274
    ;[105]
    .hword -29622, -28899, -28106, -27246, -26320, -25330, -24279, -23170
    ;[113]
    .hword -22006, -20788, -19520, -18205, -16846, -15447, -14010, -12540
    ;[121]
    .hword -11039,  -9512,  -7962,  -6393,  -4808,  -3212,  -1608

    ;===========================================================
    ; int16_t Sine16_Asm(uint16_t angle16)
    ; 入口 W0 = angle16 (  UQ0.16, 0~65535 ↔ [0,360°)  )
    ; 出口 W0 = Q1.15 正弦值
    ; 算法: index = (angle16 × SINE_TABLE_SIZE) >> 16
    ;===========================================================
    .section .text, code
    .global _Sine16_Asm
_Sine16_Asm:
    ; --- 1) 角度→索引: index = (angle16 × N) >> 16
    mov     #SINE_TABLE_SIZE, W1 ; 表点数
    mul.uu  W0, W1, W2           ; W3:W2 = (uint32)angle16<w0> × N<w1>
    mov     W3, W0               ; 高16位=整数索引(0~N-1)放到w0中; 低16位(W2)=小数部分(留作插值)
    sl      W0, #1, W0           ; 索引*2=字节偏移(每项16位=2字节; tbloffset返回字节地址)

    ; --- 2) 索引→表项: TBLRD 程序空间读取
    mov     #tblpage(_SinTable), W1
    mov     W1, TBLPAG           ; 表所在程序页
    mov     #tbloffset(_SinTable), W1 ; 正弦表基地址在在程序页中的页偏移
    add     W1, W0, W1           ; 字节地址w1 = 正弦表基址w1 + 字节偏移w0
    tblrdl  [W1], W0             ; W0 = _SinTable[index]
    return

    .end
